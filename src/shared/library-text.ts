import { hostText, type HostTextKey } from './i18n';
import type { LibraryMedia } from './library-assets';

/** Private library adapters retain existing image keys without changing public image contracts. */
export function libraryText(
  media: LibraryMedia,
  key: string,
  values?: Record<string, string | number>,
) {
  return hostText(
    (media === 'sound' && soundLibraryKeys.has(key) ? 'soundLibrary.' + key : key) as HostTextKey,
    values,
  );
}
